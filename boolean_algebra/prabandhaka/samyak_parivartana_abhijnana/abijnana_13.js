/**
 * Checks if a given AST node is a leaf (a plain logic term array).
 */
function पत्र_अस्ति(शाखा) {
    if (!Array.isArray(शाखा)) return false;
    for (let इ = 0; इ < शाखा.length; इ++) {
        if (typeof शाखा[इ] !== 'number') return false;
    }
    return true;
}

function ग्रन्थयः_समानाः(ग्रन्थि१, ग्रन्थि२) {
    if (पत्र_अस्ति(ग्रन्थि१) && पत्र_अस्ति(ग्रन्थि२)) {
        if (ग्रन्थि१.length !== ग्रन्थि२.length) return false;
        for (let इ = 0; इ < ग्रन्थि१.length; इ++) {
            if (ग्रन्थि१[इ] !== ग्रन्थि२[इ]) return false;
        }
        return true;
    }
    if (Array.isArray(ग्रन्थि१) && Array.isArray(ग्रन्थि२)) {
        if (ग्रन्थि१.length !== ग्रन्थि२.length) return false;
        if (ग्रन्थि१[0] !== ग्रन्थि२[0]) return false;
        for (let इ = 1; इ < ग्रन्थि१.length; इ++) {
            if (!ग्रन्थयः_समानाः(ग्रन्थि१[इ], ग्रन्थि२[इ])) return false;
        }
        return true;
    }
    return false;
}

function पद_चराः_प्राप्त_करो(शाखा, पितृ_संकारक) {
    if (पत्र_अस्ति(शाखा)) {
        let चराः = [];
        for (let इ = 0; इ < शाखा.length - 1; इ++) {
            if (शाखा[इ] === 0 || शाखा[इ] === 1) {
                चराः.push({ सूचकांक: इ, मूल्य: शाखा[इ] });
            } else if (शाखा[इ] === 3) {
                return null;
            }
        }
        if ((पितृ_संकारक === 1 || पितृ_संकारक === 3) && चराः.length > 1) {
            return null;
        }
        return चराः;
    } else if (Array.isArray(शाखा) && (शाखा[0] === 0 || शाखा[0] === 2)) {
        let चराः = [];
        for (let इ = 1; इ < शाखा.length; इ++) {
            let शिशु = शाखा[इ];
            if (पत्र_अस्ति(शिशु)) {
                for (let ज = 0; ज < शिशु.length - 1; ज++) {
                    if (शिशु[ज] === 0 || शिशु[ज] === 1) {
                        चराः.push({ सूचकांक: ज, मूल्य: शिशु[ज] });
                    } else if (शिशु[ज] === 3) {
                        return null;
                    }
                }
            } else {
                return null;
            }
        }
        
        let अद्वितीय_चराः = [];
        for (let च of चराः) {
            if (!अद्वितीय_चराः.some(अच => अच.सूचकांक === च.सूचकांक && अच.मूल्य === च.मूल्य)) {
                अद्वितीय_चराः.push(च);
            }
        }
        return अद्वितीय_चराः;
    }
    return null;
}

function विरोध_अन्वेषण(चराः१, चराः२) {
    let विरोधाः = [];
    for (let च१ of चराः१) {
        let च२ = चराः२.find(च => च.सूचकांक === च१.सूचकांक);
        if (च२ && च१.मूल्य !== च२.मूल्य) {
            विरोधाः.push(च१.सूचकांक);
        }
    }
    return विरोधाः;
}

/**
 * Checks if सूत्र२ is the result of applying A.B + A'.C + B.C = A.B + A'.C (Consensus Theorem) on सूत्र१.
 */
function अभिज्ञान_सम्मति(सूत्र१, सूत्र२) {
    let प्राप्त_परिवर्तनम् = 0;

    function अन्वेषणम्(ग्रन्थि१, ग्रन्थि२) {
        if (पत्र_अस्ति(ग्रन्थि१) && पत्र_अस्ति(ग्रन्थि२)) {
            return ग्रन्थयः_समानाः(ग्रन्थि१, ग्रन्थि२);
        }

        if (Array.isArray(ग्रन्थि१) && Array.isArray(ग्रन्थि२)) {
            // Check if ग्रन्थि१ is an OR node with exactly one more child than ग्रन्थि२
            if (ग्रन्थि१.length === ग्रन्थि२.length + 1 && ग्रन्थि१[0] === ग्रन्थि२[0]) {
                let संकारक = ग्रन्थि१[0];
                if (संकारक === 1 || संकारक === 3) {
                    let निष्कासित_सूचकांक = -1;
                    let match = true;
                    let j2 = 1;
                    
                    for (let j1 = 1; j1 < ग्रन्थि१.length; j1++) {
                        if (j2 < ग्रन्थि२.length && ग्रन्थयः_समानाः(ग्रन्थि१[j1], ग्रन्थि२[j2])) {
                            j2++;
                        } else if (निष्कासित_सूचकांक === -1) {
                            निष्कासित_सूचकांक = j1;
                        } else {
                            match = false;
                            break;
                        }
                    }
                    if (निष्कासित_सूचकांक === -1 && match) {
                        निष्कासित_सूचकांक = ग्रन्थि१.length - 1; 
                    }

                    if (match && निष्कासित_सूचकांक !== -1) {
                        let पदानि = [];
                        for (let इ = 1; इ < ग्रन्थि१.length; इ++) {
                            let चराः = पद_चराः_प्राप्त_करो(ग्रन्थि१[इ], संकारक);
                            if (चराः && चराः.length > 0) {
                                पदानि.push({ सूचकांक: इ, चराः: चराः });
                            }
                        }
                        
                        let प३_सूचकांक = निष्कासित_सूचकांक;
                        let प३ = पदानि.find(प => प.सूचकांक === प३_सूचकांक);
                        
                        if (प३) {
                            let सम्मति_प्राप्तम् = false;
                            for (let इ = 0; इ < पदानि.length; इ++) {
                                for (let ज = 0; ज < पदानि.length; ज++) {
                                    if (इ === ज || पदानि[इ].सूचकांक === प३_सूचकांक || पदानि[ज].सूचकांक === प३_सूचकांक) continue;
                                    
                                    let प१ = पदानि[इ];
                                    let प२ = पदानि[ज];
                                    let विरोधाः = विरोध_अन्वेषण(प१.चराः, प२.चराः);
                                    
                                    if (विरोधाः.length === 1) {
                                        let विरोध_सूचकांक = विरोधाः[0];
                                        let यज_चराः = [];
                                        for (let च of प१.चराः) {
                                            if (च.सूचकांक !== विरोध_सूचकांक) यज_चराः.push(च);
                                        }
                                        for (let च of प२.चराः) {
                                            if (च.सूचकांक !== विरोध_सूचकांक) {
                                                if (!यज_चराः.some(यज => यज.सूचकांक === च.सूचकांक)) {
                                                    यज_चराः.push(च);
                                                }
                                            }
                                        }
                                        
                                        if (यज_चराः.length > 0) {
                                            let उपसमुच्चय_अस्ति = true;
                                            for (let यज of यज_चराः) {
                                                let प्राप्तम् = प३.चराः.find(च => च.सूचकांक === यज.सूचकांक && च.मूल्य === यज.मूल्य);
                                                if (!प्राप्तम्) {
                                                    उपसमुच्चय_अस्ति = false;
                                                    break;
                                                }
                                            }
                                            if (उपसमुच्चय_अस्ति) {
                                                सम्मति_प्राप्तम् = true;
                                                break;
                                            }
                                        }
                                    }
                                }
                                if (सम्मति_प्राप्तम्) break;
                            }
                            
                            if (सम्मति_प्राप्तम्) {
                                प्राप्त_परिवर्तनम्++;
                                return true;
                            }
                        }
                    }
                }
            }

            if (ग्रन्थि१.length !== ग्रन्थि२.length) return false;
            if (ग्रन्थि१[0] !== ग्रन्थि२[0]) return false;

            for (let इ = 1; इ < ग्रन्थि१.length; इ++) {
                if (!अन्वेषणम्(ग्रन्थि१[इ], ग्रन्थि२[इ])) {
                    return false;
                }
            }
            return true;
        }

        return false;
    }

    let समान_अस्ति = अन्वेषणम्(सूत्र१, सूत्र२);
    return समान_अस्ति && प्राप्त_परिवर्तनम् === 1;
}

module.exports = {
    अभिज्ञान_सम्मति
};
