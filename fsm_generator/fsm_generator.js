  पाठः += `module tb_${यन्त्र_नाम};\n\n`;
  पाठः += `    // Clock and Reset Signals\n`;
  पाठः += `    reg clk;\n`;
  पाठः += `    reg rst_n;\n\n`;

  पाठः += `    // Input Stimulus Signals\n`;
  निवेश_संकेताः.forEach(संकेत => {
    पाठः += `    reg ${संकेत};\n`;
  });
