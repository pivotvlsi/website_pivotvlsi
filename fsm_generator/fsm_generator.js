  const शर्त_पाठ = (संवाद_शर्त_निवेशः && संवाद_शर्त_निवेशः.value.trim()) || "1'b1";
  const निर्गम_पाठ = (संवाद_निर्गम_निवेशः && संवाद_निर्गम_निवेशः.value.trim()) || 'dout = 0';

