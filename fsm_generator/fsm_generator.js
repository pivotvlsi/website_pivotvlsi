// स्थिति संपादन स्वीकारः (Save changes from state edit modal)
function स्थिति_संपादन_स्वीकारः() {
  if (!संवाद_पुनर्नाम_निवेशः) return;
  const नूतन_नाम = संवाद_पुनर्नाम_निवेशः.value.trim().replace(/\s+/g, '_');
  if (!नूतन_नाम) return;

  const पुरातन_नाम = संपादित_स्थिति_नाम;

  if (नूतन_नाम !== पुरातन_नाम && स्थितयः.includes(नूतन_नाम)) {
    alert(`State "${नूतन_नाम}" already exists!`);
    return;
  }

  // Rename in state list
  if (नूतन_नाम !== पुरातन_नाम) {
    const अनुक्रम = स्थितयः.indexOf(पुरातन_नाम);
    if (अनुक्रम !== -1) {
      स्थितयः[अनुक्रम] = नूतन_नाम;
    }
    // Rename coordinates
    नोड_स्थानानि[नूतन_नाम] = नोड_स्थानानि[पुरातन_नाम];
    delete नोड_स्थानानि[पुरातन_नाम];

    // Rename in all transitions
    संक्रमणाः.forEach(त => {
      if (त.स्रोतः === पुरातन_नाम) त.स्रोतः = नूतन_नाम;
      if (त.गन्तव्यम् === पुरातन_नाम) त.गन्तव्यम् = नूतन_नाम;
    });
  }

  // Set as reset state (move to index 0)
  if (संवाद_प्रारम्भिक_जांच && संवाद_प्रारम्भिक_जांच.checked) {
    const कार्य_नाम = (नूतन_नाम !== पुरातन_नाम) ? नूतन_नाम : पुरातन_नाम;
    स्थितयः = [कार्य_नाम, ...स्थितयः.filter(पद => पद !== कार्य_नाम)];
  }

  if (स्थिति_सूची_निवेशः) {
    स्थिति_सूची_निवेशः.value = स्थितयः.join(', ');
  }

  स्थिति_संपादन_गोपनम्();
  विकल्प_सूची_नवीकरणम्();
  सारणी_चित्रणम्();
  रेखाचित्र_अंकनम्();
  संहिता_उत्पादनम्();
  साधन_संकेत_अद्यतनीकरणम्(`State "${नूतन_नाम}" updated. Verilog HDL regenerated.`);
}

