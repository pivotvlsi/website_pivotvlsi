// नोड अन्वेषणम् (Hit-test node by coordinates)
function नोड_अन्वेषणम्(एक्स, वाय) {
  for (let सूचिका = स्थितयः.length - 1; सूचिका >= 0; सूचिका--) {
    const स्थिति_पद = स्थितयः[सूचिका];
    const नोड = नोड_स्थानानि[स्थिति_पद];
    if (नोड) {
      const दूरी = Math.hypot(एक्स - नोड.x, वाय - नोड.y);
      if (दूरी <= नोड.r) {
        return स्थिति_पद;
      }
    }
  }
  return null;
}

// संक्रमण अन्वेषणम् (Hit-test transition near curve midpoint or self-loop)
function संक्रमण_अन्वेषणम्(एक्स, वाय) {
  const विस्तार = रेखाचित्र_फलकम् ? रेखाचित्र_फलकम्.width : 800;
  const उच्चता = रेखाचित्र_फलकम् ? रेखाचित्र_फलकम्.height : 480;
  const केन्द्र_एक्स = विस्तार / 2;
  const केन्द्र_वाय = उच्चता / 2;

  for (let अनुक्रमांक = 0; अनुक्रमांक < संक्रमणाः.length; अनुक्रमांक++) {
    const संक्रमण = संक्रमणाः[अनुक्रमांक];
    const स्रोतः = नोड_स्थानानि[संक्रमण.स्रोतः];
    const गन्तव्यम् = नोड_स्थानानि[संक्रमण.गन्तव्यम्];
    if (!स्रोतः || !गन्तव्यम्) continue;

    if (संक्रमण.स्रोतः === संक्रमण.गन्तव्यम्) {
      let आधार_कोण = Math.atan2(स्रोतः.y - केन्द्र_वाय, स्रोतः.x - केन्द्र_एक्स);
      if (Math.hypot(स्रोतः.x - केन्द्र_एक्स, स्रोतः.y - केन्द्र_वाय) < 35) {
        आधार_कोण = -Math.PI / 2;
      }
      const वलय_दूरी = स्रोतः.r + 22 - 5;
      const वलय_केन्द्र_एक्स = स्रोतः.x + वलय_दूरी * Math.cos(आधार_कोण);
      const वलय_केन्द्र_वाय = स्रोतः.y + वलय_दूरी * Math.sin(आधार_कोण);

      const दूरी = Math.hypot(एक्स - वलय_केन्द्र_एक्स, वाय - वलय_केन्द्र_वाय);
      if (दूरी <= 26) {
        return अनुक्रमांक;
      }
    } else {
      const अन्तर_एक्स = गन्तव्यम्.x - स्रोतः.x;
      const अन्तर_वाय = गन्तव्यम्.y - स्रोतः.y;
      const कुल_दूरी = Math.hypot(अन्तर_एक्स, अन्तर_वाय);
      if (कुल_दूरी > 0) {
        const सामान्य_वाय = अन्तर_वाय / कुल_दूरी;
        const सामान्य_एक्स = अन्तर_एक्स / कुल_दूरी;
        const मध्य_एक्स = (स्रोतः.x + गन्तव्यम्.x) / 2 - सामान्य_वाय * 25;
        const मध्य_वाय = (स्रोतः.y + गन्तव्यम्.y) / 2 + सामान्य_एक्स * 25;
        if (Math.hypot(एक्स - मध्य_एक्स, वाय - मध्य_वाय) < 20) {
          return अनुक्रमांक;
        }
      }
    }
  }
  return -1;
}

// नोड विलोपनम् (Remove state node and its transitions)
function नोड_विलोपनम्(स्थिति_पद) {
  if (confirm(`Delete state "${स्थिति_पद}" and all its transitions?`)) {
    स्थितयः = स्थितयः.filter(पद => पद !== स्थिति_पद);
    delete नोड_स्थानानि[स्थिति_पद];
    संक्रमणाः = संक्रमणाः.filter(त => त.स्रोतः !== स्थिति_पद && त.गन्तव्यम् !== स्थिति_पद);

    if (स्थिति_सूची_निवेशः) {
      स्थिति_सूची_निवेशः.value = स्थितयः.join(', ');
    }

    विकल्प_सूची_नवीकरणम्();
    सारणी_चित्रणम्();
    रेखाचित्र_अंकनम्();
    संहिता_उत्पादनम्();
  }
}

