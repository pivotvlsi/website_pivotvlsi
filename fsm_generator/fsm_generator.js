// सारणी चित्रणम् (Render transition matrix table)
function सारणी_चित्रणम्() {
  if (!संक्रमण_सारणी_शरीरम्) return;
  संक्रमण_सारणी_शरीरम्.innerHTML = '';

  संक्रमणाः.forEach((संक्रमण, अनुक्रमांक) => {
    const पंक्ति = document.createElement('tr');
    पंक्ति.style.cursor = 'pointer';
    पंक्ति.title = 'Click row to edit/update this transition';
    पंक्ति.onclick = (घ) => {
      if (घ.target.closest('button')) return;
      संक्रमण_संवाद_प्रदर्शनम्(संक्रमण.स्रोतः, संक्रमण.गन्तव्यम्, अनुक्रमांक);
    };
    पंक्ति.innerHTML = `
      <td style="color: #38bdf8; font-weight: 600;">${संक्रमण.स्रोतः}</td>
      <td style="color: #a5b4fc; font-weight: 600;">${संक्रमण.गन्तव्यम्}</td>
      <td style="color: #fcd34d;">${संक्रमण.शर्तः}</td>
      <td style="color: #34d399;">${संक्रमण.निर्गमः}</td>
      <td>
        <button class="क्रियाकीलः लघुकीलः" onclick="संक्रमण_संवाद_प्रदर्शनम्('${संक्रमण.स्रोतः}', '${संक्रमण.गन्तव्यम्}', ${अनुक्रमांक})" title="Edit transition" style="margin-right: 4px;">
          <i class="fas fa-edit"></i>
        </button>
        <button class="क्रियाकीलः लघुकीलः क्रियाकीलः-संकट" onclick="संक्रमण_विलोपनम्(${अनुक्रमांक})" title="Delete transition">
          <i class="fas fa-times"></i>
        </button>
      </td>
    `;
    संक्रमण_सारणी_शरीरम्.appendChild(पंक्ति);
  });

  if (स्थिति_गणना_संकेतः) {
    स्थिति_गणना_संकेतः.innerHTML = `States: <strong>${स्थितयः.length}</strong> &bull; Transitions: <strong>${संक्रमणाः.length}</strong>`;
  }
}

// रेखाचित्र अंकनम् (Draw State Transition Graph on Canvas)
function रेखाचित्र_अंकनम्() {
  if (!फलक_प्रसंगः || !रेखाचित्र_फलकम्) return;
  const चित्र_प्रसंग = फलक_प्रसंगः;
  const विस्तार = रेखाचित्र_फलकम्.width;
  const उच्चता = रेखाचित्र_फलकम्.height;

  // Background clear
  चित्र_प्रसंग.clearRect(0, 0, विस्तार, उच्चता);

  // Background subtle grid
  चित्र_प्रसंग.strokeStyle = 'rgba(255, 255, 255, 0.03)';
  चित्र_प्रसंग.lineWidth = 1;
  for (let एक्स = 0; एक्स < विस्तार; एक्स += 30) {
    चित्र_प्रसंग.beginPath();
    चित्र_प्रसंग.moveTo(एक्स, 0);
    चित्र_प्रसंग.lineTo(एक्स, उच्चता);
    चित्र_प्रसंग.stroke();
  }
  for (let वाय = 0; वाय < उच्चता; वाय += 30) {
    चित्र_प्रसंग.beginPath();
    चित्र_प्रसंग.moveTo(0, वाय);
    चित्र_प्रसंग.lineTo(विस्तार, वाय);
    चित्र_प्रसंग.stroke();
  }

  // Count self loops per state to angle multiple loops gracefully
  const स्वयंवलय_गणना = {};
  const स्वयंवलय_सूचिका = {};
  संक्रमणाः.forEach(संक्रमण => {
    if (संक्रमण.स्रोतः === संक्रमण.गन्तव्यम्) {
      स्वयंवलय_गणना[संक्रमण.स्रोतः] = (स्वयंवलय_गणना[संक्रमण.स्रोतः] || 0) + 1;
    }
  });

  // Draw Transitions (Edges)
  संक्रमणाः.forEach(संक्रमण => {
    const स्रोत_नोड = नोड_स्थानानि[संक्रमण.स्रोतः];
    const गन्तव्य_नोड = नोड_स्थानानि[संक्रमण.गन्तव्यम्];
    if (!स्रोत_नोड || !गन्तव्य_नोड) return;

    if (संक्रमण.स्रोतः === संक्रमण.गन्तव्यम्) {
      const वर्तमान_सूचिका = स्वयंवलय_सूचिका[संक्रमण.स्रोतः] || 0;
      स्वयंवलय_सूचिका[संक्रमण.स्रोतः] = वर्तमान_सूचिका + 1;
      const कुल_स्वयं = स्वयंवलय_गणना[संक्रमण.स्रोतः] || 1;
      तीर_स्वयंवलय_अंकनम्(चित्र_प्रसंग, स्रोत_नोड, संक्रमण.शर्तः, वर्तमान_सूचिका, कुल_स्वयं);
    } else {
      तीर_रेखा_अंकनम्(चित्र_प्रसंग, स्रोत_नोड, गन्तव्य_नोड, संक्रमण.शर्तः);
    }
  });

  // Dynamic transition preview arrow when source node is selected
  if (सक्रिय_साधनम् === 'संक्रमण' && संक्रमण_स्रोतः_नोड && नोड_स्थानानि[संक्रमण_स्रोतः_नोड]) {
    const स्रोत_नोड = नोड_स्थानानि[संक्रमण_स्रोतः_नोड];
    चित्र_प्रसंग.save();
    चित्र_प्रसंग.setLineDash([6, 4]);
    चित्र_प्रसंग.strokeStyle = '#00d4ff';
    चित्र_प्रसंग.lineWidth = 2.2;
    चित्र_प्रसंग.beginPath();
    चित्र_प्रसंग.moveTo(स्रोत_नोड.x, स्रोत_नोड.y);
    चित्र_प्रसंग.lineTo(मूषक_स्थानम्.x, मूषक_स्थानम्.y);
    चित्र_प्रसंग.stroke();

    // Arrow tip
    const तीर_कोणः = Math.atan2(मूषक_स्थानम्.y - स्रोत_नोड.y, मूषक_स्थानम्.x - स्रोत_नोड.x);
    चित्र_प्रसंग.setLineDash([]);
    चित्र_प्रसंग.fillStyle = '#00d4ff';
    चित्र_प्रसंग.beginPath();
    चित्र_प्रसंग.moveTo(मूषक_स्थानम्.x, मूषक_स्थानम्.y);
    चित्र_प्रसंग.lineTo(
      मूषक_स्थानम्.x - 12 * Math.cos(तीर_कोणः - Math.PI / 6),
      मूषक_स्थानम्.y - 12 * Math.sin(तीर_कोणः - Math.PI / 6)
    );
    चित्र_प्रसंग.lineTo(
      मूषक_स्थानम्.x - 12 * Math.cos(तीर_कोणः + Math.PI / 6),
      मूषक_स्थानम्.y - 12 * Math.sin(तीर_कोणः + Math.PI / 6)
    );
    चित्र_प्रसंग.closePath();
    चित्र_प्रसंग.fill();
    चित्र_प्रसंग.restore();
  }

  // Draw Nodes (States)
  स्थितयः.forEach((स्थिति_पद, अनुक्रमांक) => {
    const नोड = नोड_स्थानानि[स्थिति_पद];
    if (!नोड) return;

    const प्रारम्भिक_स्थिति = (अनुक्रमांक === 0);
    const चयन_स्रोतः = (स्थिति_पद === संक्रमण_स्रोतः_नोड);
    const होवर_स्थितः = (स्थिति_पद === होवर_नोड);

    // Incoming reset transition arrow for initial reset state
    if (प्रारम्भिक_स्थिति) {
      const प्रारम्भ_तीर_एक्स = नोड.x - नोड.r - 40;
      const प्रारम्भ_तीर_वाय = नोड.y;
      const अन्त_तीर_एक्स = नोड.x - नोड.r;
      const अन्त_तीर_वाय = नोड.y;

      चित्र_प्रसंग.save();
      चित्र_प्रसंग.strokeStyle = '#38bdf8';
      चित्र_प्रसंग.lineWidth = 2.2;
      चित्र_प्रसंग.beginPath();
      चित्र_प्रसंग.moveTo(प्रारम्भ_तीर_एक्स, प्रारम्भ_तीर_वाय);
      चित्र_प्रसंग.lineTo(अन्त_तीर_एक्स, अन्त_तीर_वाय);
      चित्र_प्रसंग.stroke();

      चित्र_प्रसंग.fillStyle = '#38bdf8';
      चित्र_प्रसंग.beginPath();
      चित्र_प्रसंग.moveTo(अन्त_तीर_एक्स, अन्त_तीर_वाय);
      चित्र_प्रसंग.lineTo(अन्त_तीर_एक्स - 9, अन्त_तीर_वाय - 5);
      चित्र_प्रसंग.lineTo(अन्त_तीर_एक्स - 9, अन्त_तीर_वाय + 5);
      चित्र_प्रसंग.closePath();
      चित्र_प्रसंग.fill();

      चित्र_प्रसंग.font = 'bold 11px "Fira Code", monospace';
      चित्र_प्रसंग.fillStyle = '#38bdf8';
      चित्र_प्रसंग.textAlign = 'right';
      चित्र_प्रसंग.fillText('rst_n', प्रारम्भ_तीर_एक्स - 5, प्रारम्भ_तीर_वाय + 4);
      चित्र_प्रसंग.restore();
    }

    // Outer glow
    if (चयन_स्रोतः) {
      चित्र_प्रसंग.shadowColor = '#f59e0b';
      चित्र_प्रसंग.shadowBlur = 22;
    } else if (होवर_स्थितः && सक्रिय_साधनम् === 'विलोपन') {
      चित्र_प्रसंग.shadowColor = '#ef4444';
      चित्र_प्रसंग.shadowBlur = 18;
    } else if (होवर_स्थितः) {
      चित्र_प्रसंग.shadowColor = '#00d4ff';
      चित्र_प्रसंग.shadowBlur = 16;
    } else {
      चित्र_प्रसंग.shadowColor = प्रारम्भिक_स्थिति ? 'rgba(56, 189, 248, 0.6)' : 'rgba(129, 140, 248, 0.4)';
      चित्र_प्रसंग.shadowBlur = 12;
    }

    // Node fill
    चित्र_प्रसंग.beginPath();
    चित्र_प्रसंग.arc(नोड.x, नोड.y, नोड.r, 0, 2 * Math.PI);
    if (चयन_स्रोतः) {
      चित्र_प्रसंग.fillStyle = 'rgba(245, 158, 11, 0.3)';
    } else if (होवर_स्थितः && सक्रिय_साधनम् === 'विलोपन') {
      चित्र_प्रसंग.fillStyle = 'rgba(239, 68, 68, 0.3)';
    } else {
      चित्र_प्रसंग.fillStyle = प्रारम्भिक_स्थिति ? 'rgba(14, 165, 233, 0.25)' : 'rgba(15, 23, 42, 0.85)';
    }
    चित्र_प्रसंग.fill();

    // Node stroke
    चित्र_प्रसंग.lineWidth = चयन_स्रोतः ? 3.5 : (प्रारम्भिक_स्थिति ? 3 : 2);
    if (चयन_स्रोतः) {
      चित्र_प्रसंग.strokeStyle = '#f59e0b';
    } else if (होवर_स्थितः && सक्रिय_साधनम् === 'विलोपन') {
      चित्र_प्रसंग.strokeStyle = '#ef4444';
    } else if (होवर_स्थितः) {
      चित्र_प्रसंग.strokeStyle = '#00d4ff';
    } else {
      चित्र_प्रसंग.strokeStyle = प्रारम्भिक_स्थिति ? '#38bdf8' : 'rgba(255, 255, 255, 0.35)';
    }
    चित्र_प्रसंग.stroke();
    चित्र_प्रसंग.shadowBlur = 0;

    // Double circle for reset state
    if (प्रारम्भिक_स्थिति) {
      चित्र_प्रसंग.beginPath();
      चित्र_प्रसंग.arc(नोड.x, नोड.y, नोड.r - 5, 0, 2 * Math.PI);
      चित्र_प्रसंग.strokeStyle = '#0284c7';
      चित्र_प्रसंग.lineWidth = 1.5;
      चित्र_प्रसंग.stroke();
    }

    // Node label
    चित्र_प्रसंग.fillStyle = '#f8fafc';
    चित्र_प्रसंग.font = 'bold 12px "Fira Code", monospace';
    चित्र_प्रसंग.textAlign = 'center';
    चित्र_प्रसंग.textBaseline = 'middle';
    चित्र_प्रसंग.fillText(स्थिति_पद, नोड.x, नोड.y);
  });
}

// तीर रेखा अंकनम् (Draw curved transition arrow)
function तीर_रेखा_अंकनम्(चित्र_प्रसंग, स्रोतः_नोड, गन्तव्य_नोड, चिह्न_पाठ) {
  const अन्तर_एक्स = गन्तव्य_नोड.x - स्रोतः_नोड.x;
  const अन्तर_वाय = गन्तव्य_नोड.y - स्रोतः_नोड.y;
  const कुल_दूरी = Math.hypot(अन्तर_एक्स, अन्तर_वाय);
  if (कुल_दूरी === 0) return;

  const सामान्य_एक्स = अन्तर_एक्स / कुल_दूरी;
  const सामान्य_वाय = अन्तर_वाय / कुल_दूरी;

  const प्रारम्भ_एक्स = स्रोतः_नोड.x + सामान्य_एक्स * स्रोतः_नोड.r;
  const प्रारम्भ_वाय = स्रोतः_नोड.y + सामान्य_वाय * स्रोतः_नोड.r;
  const अन्त_एक्स = गन्तव्य_नोड.x - सामान्य_एक्स * गन्तव्य_नोड.r;
  const अन्त_वाय = गन्तव्य_नोड.y - सामान्य_वाय * गन्तव्य_नोड.r;

  const मध्य_एक्स = (प्रारम्भ_एक्स + अन्त_एक्स) / 2 - सामान्य_वाय * 25;
  const मध्य_वाय = (प्रारम्भ_वाय + अन्त_वाय) / 2 + सामान्य_एक्स * 25;

  चित्र_प्रसंग.strokeStyle = 'rgba(56, 189, 248, 0.65)';
  चित्र_प्रसंग.lineWidth = 1.8;
  चित्र_प्रसंग.beginPath();
  चित्र_प्रसंग.moveTo(प्रारम्भ_एक्स, प्रारम्भ_वाय);
  चित्र_प्रसंग.quadraticCurveTo(मध्य_एक्स, मध्य_वाय, अन्त_एक्स, अन्त_वाय);
  चित्र_प्रसंग.stroke();

  const तीर_कोणः = Math.atan2(अन्त_वाय - मध्य_वाय, अन्त_एक्स - मध्य_एक्स);
  const तीर_दैर्घ्यम् = 9;
  चित्र_प्रसंग.fillStyle = '#38bdf8';
  चित्र_प्रसंग.beginPath();
  चित्र_प्रसंग.moveTo(अन्त_एक्स, अन्त_वाय);
  चित्र_प्रसंग.lineTo(
    अन्त_एक्स - तीर_दैर्घ्यम् * Math.cos(तीर_कोणः - Math.PI / 7),
    अन्त_वाय - तीर_दैर्घ्यम् * Math.sin(तीर_कोणः - Math.PI / 7)
  );
  चित्र_प्रसंग.lineTo(
    अन्त_एक्स - तीर_दैर्घ्यम् * Math.cos(तीर_कोणः + Math.PI / 7),
    अन्त_वाय - तीर_दैर्घ्यम् * Math.sin(तीर_कोणः + Math.PI / 7)
  );
  चित्र_प्रसंग.closePath();
  चित्र_प्रसंग.fill();

  चित्र_प्रसंग.font = '10px "Fira Code", monospace';
  चित्र_प्रसंग.fillStyle = '#fcd34d';
  चित्र_प्रसंग.textAlign = 'center';
  चित्र_प्रसंग.fillText(चिह्न_पाठ, मध्य_एक्स, मध्य_वाय - 4);
}

// तीर स्वयंवलय अंकनम् (Draw outward directed self-loop transition)
function तीर_स्वयंवलय_अंकनम्(चित्र_प्रसंग, स्रोतः_नोड, चिह्न_पाठ, सूचिका_मान, कुल_मान) {
  const विस्तार = रेखाचित्र_फलकम् ? रेखाचित्र_फलकम्.width : 800;
  const उच्चता = रेखाचित्र_फलकम् ? रेखाचित्र_फलकम्.height : 480;
  const केन्द्र_एक्स = विस्तार / 2;
  const केन्द्र_वाय = उच्चता / 2;

  let आधार_कोण = Math.atan2(स्रोतः_नोड.y - केन्द्र_वाय, स्रोतः_नोड.x - केन्द्र_एक्स);
  if (Math.hypot(स्रोतः_नोड.x - केन्द्र_एक्स, स्रोतः_नोड.y - केन्द्र_वाय) < 35) {
    आधार_कोण = -Math.PI / 2;
  }

  const विक्षेप_कोण = (कुल_मान > 1) ? (सूचिका_मान - (कुल_मान - 1) / 2) * 0.45 : 0;
  const प्रभावी_कोण = आधार_कोण + विक्षेप_कोण;

  const वलय_त्रिज्या = 22;
  const वलय_दूरी = स्रोतः_नोड.r + वलय_त्रिज्या - 5;
  const वलय_केन्द्र_एक्स = स्रोतः_नोड.x + वलय_दूरी * Math.cos(प्रभावी_कोण);
  const वलय_केन्द्र_वाय = स्रोतः_नोड.y + वलय_दूरी * Math.sin(प्रभावी_कोण);

  // Arc path from entry to exit
  const चाप_प्रारम्भ = प्रभावी_कोण + 0.72 * Math.PI;
  const चाप_अन्त = प्रभावी_कोण - 0.72 * Math.PI;

  चित्र_प्रसंग.save();
  चित्र_प्रसंग.strokeStyle = 'rgba(251, 191, 36, 0.85)';
  चित्र_प्रसंग.lineWidth = 2;
  चित्र_प्रसंग.beginPath();
  चित्र_प्रसंग.arc(वलय_केन्द्र_एक्स, वलय_केन्द्र_वाय, वलय_त्रिज्या, चाप_प्रारम्भ, चाप_अन्त, false);
  चित्र_प्रसंग.stroke();

  // Arrowhead pointing back into the state circle
  const अग्र_बिन्दु_एक्स = वलय_केन्द्र_एक्स + वलय_त्रिज्या * Math.cos(चाप_अन्त);
  const अग्र_बिन्दु_वाय = वलय_केन्द्र_वाय + वलय_त्रिज्या * Math.sin(चाप_अन्त);
  const स्पर्श_कोण = चाप_अन्त + Math.PI / 2;
  const तीर_दैर्घ्य = 8;

  चित्र_प्रसंग.fillStyle = '#fbbf24';
  चित्र_प्रसंग.beginPath();
  चित्र_प्रसंग.moveTo(अग्र_बिन्दु_एक्स, अग्र_बिन्दु_वाय);
  चित्र_प्रसंग.lineTo(
    अग्र_बिन्दु_एक्स - तीर_दैर्घ्य * Math.cos(स्पर्श_कोण - Math.PI / 6),
    अग्र_बिन्दु_वाय - तीर_दैर्घ्य * Math.sin(स्पर्श_कोण - Math.PI / 6)
  );
  चित्र_प्रसंग.lineTo(
    अग्र_बिन्दु_एक्स - तीर_दैर्घ्य * Math.cos(स्पर्श_कोण + Math.PI / 6),
    अग्र_बिन्दु_वाय - तीर_दैर्घ्य * Math.sin(स्पर्श_कोण + Math.PI / 6)
  );
  चित्र_प्रसंग.closePath();
  चित्र_प्रसंग.fill();

  // Condition / output label
  const लेबल_दूरी = वलय_त्रिज्या + 12;
  const लेबल_एक्स = वलय_केन्द्र_एक्स + लेबल_दूरी * Math.cos(प्रभावी_कोण);
  const लेबल_वाय = वलय_केन्द्र_वाय + लेबल_दूरी * Math.sin(प्रभावी_कोण);

  चित्र_प्रसंग.font = 'bold 10px "Fira Code", monospace';
  चित्र_प्रसंग.fillStyle = '#fcd34d';
  चित्र_प्रसंग.textAlign = 'center';
  चित्र_प्रसंग.textBaseline = 'middle';
  चित्र_प्रसंग.fillText(चिह्न_पाठ, लेबल_एक्स, लेबल_वाय);
  चित्र_प्रसंग.restore();
}

