// कैनवास घटना संयोजनम् (Canvas click, drag, and double-click interactions)
function कैनवास_घटना_संयोजनम्() {
  if (!रेखाचित्र_फलकम्) return;

  रेखाचित्र_फलकम्.addEventListener('mousedown', (घटना) => {
    const निर्देशांकः = मूषक_निर्देशाङ्क_प्राप्तिः(घटना);
    const मूषक_एक्स = निर्देशांकः.x;
    const मूषक_वाय = निर्देशांकः.y;
    मूषक_सञ्चलनम्_जातम् = false;

    const अन्वेषित_नोड_नाम = नोड_अन्वेषणम्(मूषक_एक्स, मूषक_वाय);

    if ((सक्रिय_साधनम् === 'चयन' || सक्रिय_साधनम् === 'नोड') && अन्वेषित_नोड_नाम) {
      if (सक्रिय_साधनम् === 'चयन' && घटना.shiftKey) {
        // Shift + Click shortcut in Move mode to initiate transition directly!
        संक्रमण_स्रोतः_नोड = अन्वेषित_नोड_नाम;
        साधन_संकेत_अद्यतनीकरणम्(`Source: "${अन्वेषित_नोड_नाम}" selected. Click target state to connect.`);
        रेखाचित्र_अंकनम्();
        return;
      }
      घसीट_नोड = नोड_स्थानानि[अन्वेषित_नोड_नाम];
      घसीट_प्रारम्भ_बिन्दु = { x: मूषक_एक्स - घसीट_नोड.x, y: मूषक_वाय - घसीट_नोड.y };
      रेखाचित्र_फलकम्.style.cursor = 'grabbing';
    }
  });

  window.addEventListener('mousemove', (घटना) => {
    if (!रेखाचित्र_फलकम्) return;
    const निर्देशांकः = मूषक_निर्देशाङ्क_प्राप्तिः(घटना);
    const मूषक_एक्स = निर्देशांकः.x;
    const मूषक_वाय = निर्देशांकः.y;

    मूषक_स्थानम् = { x: मूषक_एक्स, y: मूषक_वाय };

    const पूर्व_होवर = होवर_नोड;
    if (मूषक_एक्स >= 0 && मूषक_एक्स <= रेखाचित्र_फलकम्.width && मूषक_वाय >= 0 && मूषक_वाय <= रेखाचित्र_फलकम्.height) {
      होवर_नोड = नोड_अन्वेषणम्(मूषक_एक्स, मूषक_वाय);
      if (सक्रिय_साधनम् === 'चयन' && !घसीट_नोड) {
        रेखाचित्र_फलकम्.style.cursor = होवर_नोड ? 'grab' : 'default';
      }
    } else {
      होवर_नोड = null;
    }

    if (घसीट_नोड) {
      मूषक_सञ्चलनम्_जातम् = true;
      let नूतन_एक्स = मूषक_एक्स - घसीट_प्रारम्भ_बिन्दु.x;
      let नूतन_वाय = मूषक_वाय - घसीट_प्रारम्भ_बिन्दु.y;

      नूतन_एक्स = Math.max(घसीट_नोड.r + 5, Math.min(रेखाचित्र_फलकम्.width - घसीट_नोड.r - 5, नूतन_एक्स));
      नूतन_वाय = Math.max(घसीट_नोड.r + 5, Math.min(रेखाचित्र_फलकम्.height - घसीट_नोड.r - 5, नूतन_वाय));

      घसीट_नोड.x = नूतन_एक्स;
      घसीट_नोड.y = नूतन_वाय;
      रेखाचित्र_अंकनम्();
    } else if (संक्रमण_स्रोतः_नोड) {
      रेखाचित्र_अंकनम्();
    } else if (पूर्व_होवर !== होवर_नोड) {
      रेखाचित्र_अंकनम्();
    }
  });

  window.addEventListener('mouseup', () => {
    if (घसीट_नोड) {
      घसीट_नोड = null;
      if (रेखाचित्र_फलकम्) {
        if (सक्रिय_साधनम् === 'चयन') रेखाचित्र_फलकम्.style.cursor = होवर_नोड ? 'grab' : 'default';
        else if (सक्रिय_साधनम् === 'नोड') रेखाचित्र_फलकम्.style.cursor = 'crosshair';
        else if (सक्रिय_साधनम् === 'संक्रमण') रेखाचित्र_फलकम्.style.cursor = 'crosshair';
        else if (सक्रिय_साधनम् === 'विलोपन') रेखाचित्र_फलकम्.style.cursor = 'pointer';
      }
    }
  });

  // Single Click handling for creating state, transition, or deleting
  रेखाचित्र_फलकम्.addEventListener('click', (घटना) => {
    if (मूषक_सञ्चलनम्_जातम्) {
      मूषक_सञ्चलनम्_जातम् = false;
      return;
    }

    const निर्देशांकः = मूषक_निर्देशाङ्क_प्राप्तिः(घटना);
    const मूषक_एक्स = निर्देशांकः.x;
    const मूषक_वाय = निर्देशांकः.y;
    const अन्वेषित_नोड_नाम = नोड_अन्वेषणम्(मूषक_एक्स, मूषक_वाय);

    if (संक्रमण_स्रोतः_नोड) {
      // Complete transition whether in 'संक्रमण' mode or via Shift+click
      if (अन्वेषित_नोड_नाम) {
        const स्रोतः_पद = संक्रमण_स्रोतः_नोड;
        const गन्तव्य_पद = अन्वेषित_नोड_नाम;
        संक्रमण_स्रोतः_नोड = null;
        संक्रमण_संवाद_प्रदर्शनम्(स्रोतः_पद, गन्तव्य_पद);
      } else {
        संक्रमण_स्रोतः_नोड = null;
        साधन_संकेत_अद्यतनीकरणम्('Transition selection cancelled.');
        रेखाचित्र_अंकनम्();
      }
      return;
    }

    if (सक्रिय_साधनम् === 'चयन') {
      if (!अन्वेषित_नोड_नाम) {
        const संक्रमण_अनुक्रमांक = संक्रमण_अन्वेषणम्(मूषक_एक्स, मूषक_वाय);
        if (संक्रमण_अनुक्रमांक !== -1) {
          const लक्ष्य_संक्रमण = संक्रमणाः[संक्रमण_अनुक्रमांक];
          संक्रमण_संवाद_प्रदर्शनम्(लक्ष्य_संक्रमण.स्रोतः, लक्ष्य_संक्रमण.गन्तव्यम्, संक्रमण_अनुक्रमांक);
          return;
        }
      }
    }

    if (सक्रिय_साधनम् === 'नोड') {
      if (!अन्वेषित_नोड_नाम) {
        स्थिति_संवाद_प्रदर्शनम्(मूषक_एक्स, मूषक_वाय);
      } else {
        साधन_संकेत_अद्यतनीकरणम्(`State "${अन्वेषित_नोड_नाम}" already exists at this point. Click empty space to add state.`);
      }
    } else if (सक्रिय_साधनम् === 'संक्रमण') {
      if (अन्वेषित_नोड_नाम) {
        संक्रमण_स्रोतः_नोड = अन्वेषित_नोड_नाम;
        साधन_संकेत_अद्यतनीकरणम्(`Source: "${अन्वेषित_नोड_नाम}" selected. Now click target state (or same state for self-loop).`);
        रेखाचित्र_अंकनम्();
      }
    } else if (सक्रिय_साधनम् === 'विलोपन') {
      if (अन्वेषित_नोड_नाम) {
        नोड_विलोपनम्(अन्वेषित_नोड_नाम);
      } else {
        const संक्रमण_अनुक्रमांक = संक्रमण_अन्वेषणम्(मूषक_एक्स, मूषक_वाय);
        if (संक्रमण_अनुक्रमांक !== -1) {
          if (confirm('Delete this transition?')) {
            संक्रमण_विलोपनम्(संक्रमण_अनुक्रमांक);
            साधन_संकेत_अद्यतनीकरणम्('Transition deleted.');
          }
        }
      }
    }
  });

  // Double Click handling: empty canvas creates state; existing state opens edit modal
  रेखाचित्र_फलकम्.addEventListener('dblclick', (घटना) => {
    const निर्देशांकः = मूषक_निर्देशाङ्क_प्राप्तिः(घटना);
    const मूषक_एक्स = निर्देशांकः.x;
    const मूषक_वाय = निर्देशांकः.y;
    const अन्वेषित_नोड_नाम = नोड_अन्वेषणम्(मूषक_एक्स, मूषक_वाय);

    if (!अन्वेषित_नोड_नाम) {
      स्थिति_संवाद_प्रदर्शनम्(मूषक_एक्स, मूषक_वाय);
    } else {
      स्थिति_संपादन_प्रदर्शनम्(अन्वेषित_नोड_नाम);
    }
  });
}

